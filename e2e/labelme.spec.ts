// labelme's features, one area at a time, checked in the files they write

const near = (a: number[], b: number[], tolerance = 3) => Math.hypot(a[0] - b[0], a[1] - b[1]) <= tolerance
const tool = (page: import('@playwright/test').Page, name: string) => page.getByRole('toolbar').getByRole('button', { name, exact: true }).click()

test('every labelme shape type, saved as labelme saves it', async () => {
  const dir = await project('shapes', { s: null })
  const { app, page, errors } = await launch(dir, ['--labels', 'cat,dog'])
  await open(page, 's.png')
  // Polygon: closes on the first point
  await page.keyboard.press('p')
  for (const [x, y] of [[20, 20], [120, 20], [120, 90]]) await click(page, x, y)
  await click(page, 20, 20)
  // Rectangle by dragging, then one by two clicks with Shift for a square
  await page.keyboard.press('r')
  await drag(page, [150, 20], [220, 80])
  await click(page, 240, 20)
  await page.keyboard.down('Shift')
  await click(page, 300, 60)
  await page.keyboard.up('Shift')
  await tool(page, 'Circle')
  await click(page, 60, 200)
  await click(page, 90, 200)
  await tool(page, 'Line')
  await click(page, 150, 150)
  await click(page, 250, 160)
  await tool(page, 'Line strip')
  for (const [x, y] of [[150, 220], [200, 260], [260, 230]]) await click(page, x, y)
  await page.keyboard.press('Enter')
  await tool(page, 'Point')
  await click(page, 350, 250)
  await expect(page.locator('.shape')).toHaveCount(7)
  await saved(page)
  const shapes = shapesIn(dir, 's')
  expect(shapes.map((s: any) => s.shape_type)).toEqual(['polygon', 'rectangle', 'rectangle', 'circle', 'line', 'linestrip', 'point'])
  expect(shapes.every((s: any) => s.label === 'cat' && s.mask === null && s.group_id === null && s.description === '')).toBe(true)
  expect(Object.keys(shapes[0])).toEqual(['label', 'points', 'group_id', 'description', 'shape_type', 'flags', 'mask'])
  expect(shapes[0].points).toHaveLength(3)
  expect(near(shapes[1].points[1], [220, 80])).toBe(true)
  const [[a, b], [c, d]] = shapes[2].points
  expect(Math.abs(Math.abs(c - a) - Math.abs(d - b))).toBeLessThan(0.01)
  expect(near(shapes[3].points[1], [90, 200])).toBe(true)
  expect(shapes[5].points).toHaveLength(3)
  expect(shapes[6].points).toHaveLength(1)
  expect(read(dir, 's').imagePath).toBe('s.png')
  expect([read(dir, 's').imageWidth, read(dir, 's').imageHeight]).toEqual([400, 300])
  await finish(app, errors)
})

test('the label dialog: completion, flags by label, group ID, description', async () => {
  const dir = await project('dialog', { q: null })
  const { app, page, errors } = await launch(dir, ['--labels', 'cat,dog,dolphin', '--labelflags', '{cat: [occluded, truncated], "do.*": [wet]}',
    '--config', '{display_label_popup: true}'])
  await open(page, 'q.png')
  await page.keyboard.press('r')
  await drag(page, [50, 50], [150, 150])
  const dialog = page.getByRole('dialog', { name: 'Label' })
  await expect(dialog).toBeVisible()
  await dialog.getByLabel('Label', { exact: true }).fill('do')
  await expect(dialog.getByRole('option')).toHaveText(['dog', 'dolphin'])
  await expect(dialog.getByLabel('wet')).toBeVisible()
  await dialog.getByLabel('Label', { exact: true }).fill('cat')
  await expect(dialog.getByLabel('wet')).toHaveCount(0)
  await dialog.getByLabel('occluded').check()
  await dialog.getByLabel('Group ID').fill('2')
  await dialog.getByLabel('Description').fill('left one')
  await dialog.getByRole('button', { name: 'OK' }).click()
  await saved(page)
  let [s] = shapesIn(dir, 'q')
  expect(s).toMatchObject({ label: 'cat', group_id: 2, description: 'left one', flags: { occluded: true, truncated: false } })
  // Cancelling a new shape keeps nothing
  await drag(page, [200, 50], [300, 150])
  await expect(dialog).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
  await expect(page.locator('.shape')).toHaveCount(1)
  // Edit label: the list's double-click, as in labelme; a new label swaps in its own flags
  await page.locator('.shape').first().dblclick()
  const edit = page.getByRole('dialog', { name: 'Edit label' })
  await expect(edit.getByLabel('Label', { exact: true })).toHaveValue('cat')
  await expect(edit.getByLabel('Group ID')).toHaveValue('2')
  await edit.getByLabel('Label', { exact: true }).fill('dog')
  await edit.getByLabel('Label', { exact: true }).press('Enter')
  await saved(page)
  ;[s] = shapesIn(dir, 'q')
  expect(s).toMatchObject({ label: 'dog', group_id: 2, description: 'left one', flags: { wet: false } })
  expect(s.flags.occluded).toBeUndefined()
  await expect(page.locator('.shape').first()).toContainText('dog (2)')
  await finish(app, errors)
})

