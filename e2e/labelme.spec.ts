test('keep previous annotation, and Ctrl+Shift+D to copy once', async () => {
  const dir = await project('keep', { a: doc('a', [square('cat', 50, 50, 150, 150)]), b: null, c: null })
  const { app, page, errors } = await launch(dir)
  await open(page, 'a.png')
  await page.keyboard.press('ControlOrMeta+Shift+d')
  await expect(page.locator('.file.on')).toContainText('b.png')
  // The list moves to b at once; a's shape and its "Saved" show until b has loaded
  await expect.poll(() => existsSync(path.join(dir, 'b.json')) && shapesIn(dir, 'b').length).toBe(1)
  await expect(page.locator('.shape')).toHaveCount(1)
  await saved(page)
  await page.keyboard.press('d')
  await expect(page.locator('.file.on')).toContainText('c.png')
  await expect(page.locator('.shape')).toHaveCount(0)
  expect(existsSync(path.join(dir, 'c.json'))).toBe(false)
  await page.keyboard.press('a')
  // labelme 7 gave Keep Previous Annotation no key; it's in the Edit menu
  await page.getByRole('menuitem', { name: 'Edit' }).click()
  await page.getByRole('menuitemcheckbox', { name: 'Keep previous annotation' }).click()
  await page.keyboard.press('d')
  await expect(page.locator('.shape')).toHaveCount(1)
  await expect.poll(() => existsSync(path.join(dir, 'c.json')) && shapesIn(dir, 'c').length).toBe(1)
  await finish(app, errors)
})

test('an output folder, image data in the file, and a label file opened on its own', async () => {
  const dir = await project('output', { o: null }, [{ name: 'cat', color: '#4f8cff' }])
  const out = path.join(BASE, 'output-labels')
  rmSync(out, { recursive: true, force: true })
  let { app, page, errors } = await launch(dir, ['-O', out])
  await open(page, 'o.png')
  await page.keyboard.press('r')
  await drag(page, [50, 50], [150, 150])
  await saved(page)
  expect(existsSync(path.join(dir, 'o.json'))).toBe(false)
  expect(read(out, 'o').imagePath).toBe('../output/o.png')
  await page.getByRole('menuitem', { name: 'File' }).click()
  await page.getByRole('menuitemcheckbox', { name: 'Save with image data' }).click()
  await page.keyboard.press('ControlOrMeta+s')
  await saved(page)
  const data = read(out, 'o').imageData
  expect(Buffer.from(data, 'base64').subarray(1, 4).toString()).toBe('PNG')
  await finish(app, errors)

  // labelme can open a label file whose image only lives inside it
  const alone = path.join(BASE, 'embedded')
  rmSync(alone, { recursive: true, force: true })
  mkdirSync(alone, { recursive: true })
  writeFileSync(path.join(alone, 'only.json'), JSON.stringify({ ...JSON.parse(readFileSync(path.join(out, 'o.json'), 'utf8')), imagePath: 'gone.png' }))
  ;({ app, page, errors } = await launch(path.join(alone, 'only.json')))
  await expect(page.locator('.status')).toContainText('400 × 300')
  await expect(page.locator('.shape')).toHaveCount(1)
  await page.locator('.shape').first().click()
  await page.keyboard.press('Delete')
  await expect(page.locator('.shape')).toHaveCount(0)
  await saved(page)
  const kept = JSON.parse(readFileSync(path.join(alone, 'only.json'), 'utf8'))
  expect(kept.imageData).toBe(data)
  expect(kept.imagePath).toBe('gone.png')
  await finish(app, errors)
})

