test('copy, paste, duplicate, delete, undo and merge', async () => {
  const dir = await project('edit', {
    a: doc('a', [square('cat', 50, 50, 150, 150), square('cat', 120, 120, 220, 220), square('dog', 300, 50, 350, 100)]),
    b: null
  })
  const { app, page, errors } = await launch(dir)
  await open(page, 'a.png')
  await page.keyboard.press('v')
  await page.locator('.shape').nth(2).click()
  await page.keyboard.press('ControlOrMeta+c')
  await open(page, 'b.png')
  await page.keyboard.press('ControlOrMeta+v')
  await saved(page)
  expect(shapesIn(dir, 'b')).toHaveLength(1)
  expect(shapesIn(dir, 'b')[0].label).toBe('dog')
  await page.keyboard.press('ControlOrMeta+d')
  await expect(page.locator('.shape')).toHaveCount(2)
  await page.keyboard.press('Delete')
  await expect(page.locator('.shape')).toHaveCount(1)
  await page.keyboard.press('ControlOrMeta+z')
  await expect(page.locator('.shape')).toHaveCount(2)
  await open(page, 'a.png')
  await page.locator('.shape').nth(0).click()
  await page.locator('.shape').nth(1).click({ modifiers: ['ControlOrMeta'] })
  await page.keyboard.press('ControlOrMeta+Shift+m')
  await expect(page.locator('.shape')).toHaveCount(2)
  await saved(page)
  const merged = shapesIn(dir, 'a')
  expect(merged.map((s: any) => s.label)).toEqual(['cat', 'dog'])
  expect(merged[0].points.length).toBeGreaterThan(4)
  // Arrow keys nudge the selection, Shift by 10
  await page.locator('.shape').nth(1).click()
  await page.keyboard.press('Shift+ArrowRight')
  await page.keyboard.press('ArrowDown')
  await saved(page)
  expect(shapesIn(dir, 'a')[1].points[0]).toEqual([310, 51])
  await finish(app, errors)
})

