test('a very large TIFF opens through a tile pyramid', async () => {
  test.setTimeout(180000)
  const dir = await project('large', {})
  await sharp({ create: { width: 6050, height: 12300, channels: 3, background: '#30343a' } })
    .composite([{ input: Buffer.from('<svg width="2000" height="2000"><circle cx="1000" cy="1000" r="1000" fill="#e6b43c"/></svg>'), left: 2000, top: 5000 }])
    .tiff({ compression: 'lzw' }).toFile(path.join(dir, 'big.tif'))
  const { app, page, errors } = await launch(dir, ['--labels', 'disc'])
  await open(page, 'big.tif')
  await expect(page.locator('.status')).toContainText('6050 × 12300')
  const ms = await page.evaluate(async (root) => {
    const t = performance.now()
    await window.api.openImage(root, 'big.tif')
    return performance.now() - t
  }, dir)
  // Built once, then reused
  expect(ms).toBeLessThan(1000)
  await page.keyboard.press('r')
  await page.mouse.move(...await onImage(page, 2000, 5000, 6050, 12300))
  await page.mouse.down()
  await page.mouse.move(...await onImage(page, 4000, 7000, 6050, 12300), { steps: 6 })
  await page.mouse.up()
  await saved(page)
  const [shape] = shapesIn(dir, 'big')
  expect(near(shape.points[0], [2000, 5000], 40)).toBe(true)
  expect(read(dir, 'big').imageWidth).toBe(6050)
  await finish(app, errors)
})

